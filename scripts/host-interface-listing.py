import pathlib
import re
import sys

root = pathlib.Path(__file__).resolve().parent.parent
tools_path = root / "src/builtins/tools.zig"
tools_text = tools_path.read_text()
lines = tools_text.splitlines()

spec_line = re.compile(r'^pub const (\w+) = ToolSpec\{')
name_line = re.compile(r'^\s*\.name = "([^"]+)"')
direct = {}
for number, line in enumerate(lines, 1):
    match = spec_line.match(line)
    if not match:
        continue
    for follow in lines[number:number + 4]:
        name = name_line.match(follow)
        if name:
            direct[match.group(1)] = (name.group(1), f"src/builtins/tools.zig:{number}")
            break

start = next(i for i, line in enumerate(lines) if line.startswith("const verb_tools = "))
members = []
for line in lines[start + 1:]:
    if line.startswith("};"):
        break
    symbol = line.strip().rstrip(",")
    if symbol:
        members.append(symbol)

tower = []
tower_dir = root / "src/tools/tower"
for path in sorted(tower_dir.glob("*.zig")):
    text = path.read_text()
    match = re.search(r'pub const spec = ToolSpec\{\s*\.name = "([^"]+)"', text)
    if match:
        tower.append((match.group(1), f"{path.relative_to(root)}"))

rows = ["| tool | registry symbol | source |", "| --- | --- | --- |", "| run_code | run_code | src/builtins/tools.zig |"]
unresolved = 0
for symbol in members:
    if symbol in direct:
        name, source = direct[symbol]
        rows.append(f"| {name} | {symbol} | {source} |")
    else:
        unresolved += 1
        rows.append(f"| (resolved at runtime) | {symbol} | src/builtins/tools.zig |")
for name, source in tower:
    rows.append(f"| {name} | Tower | {source} |")

out = [
    "# Host interface tool listing",
    "",
    "Generated by scripts/host-interface-listing.py from src/builtins/tools.zig (verb_tools registry members) and src/tools/tower/*.zig (Tower specs). Do not edit by hand; rerun the script.",
    "",
] + rows + [
    "",
    f"Total: {len(members) + 1 + len(tower)} registry entries: run_code, {len(members)} verb_tools members ({len(members) - unresolved} resolved by name, {unresolved} resolved at runtime), {len(tower)} Tower.",
]
target = root / "docs/host-interface-listing.md"
target.write_text("\n".join(out) + "\n")
print(f"wrote {target.relative_to(root)}: {len(members) + 1 + len(tower)} entries")
sys.exit(0)
