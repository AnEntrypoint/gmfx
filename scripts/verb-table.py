import pathlib
import re
import sys

root = pathlib.Path(__file__).resolve().parent.parent
host_text = (root / "src/core/runcode/host_verbs.zig").read_text()
start = host_text.index("pub const verbs = [_]Verb{")
end = host_text.index("\n};", start)
body = host_text[start:end]
blocks = re.split(r"\n    \.\{\n", body)[1:]
host_rows = []
for block in blocks:
    name = re.search(r'\.name = "([^"]+)"', block).group(1)
    description = re.search(r'\.description = "((?:[^"\\]|\\.)*)"', block).group(1)
    properties = re.findall(r'\.\{ \.name = "([^"]+)", \.json_type = \.(\w+)', block)
    required = re.search(r"\.required = &\.\{([^}]*)\}", block)
    required_names = re.findall(r'"([^"]+)"', required.group(1)) if required else []
    schema = ", ".join(f"{pname}: {ptype}{' (required)' if pname in required_names else ''}" for pname, ptype in properties)
    host_rows.append((name, description, schema or "none"))

tools_text = (root / "src/builtins/tools.zig").read_text()
verb_start = tools_text.index("const verb_tools = [_]tool_dispatch.Tool{")
verb_end = tools_text.index("};", verb_start)
members = [line.strip().rstrip(",") for line in tools_text[verb_start:verb_end].splitlines()[1:] if line.strip()]

out = [
    "# Verb table",
    "",
    "Generated by scripts/verb-table.py from src/core/runcode/host_verbs.zig (host verbs, with their input schemas) and src/builtins/tools.zig (the registry members). Do not edit by hand; rerun the script.",
    "",
    "## Host verbs (gm-style, the tools.* services as verbs of run_code)",
    "",
    "| verb | description | input (name: json type) |",
    "| --- | --- | --- |",
]
for name, description, schema in host_rows:
    out.append(f"| {name} | {description} | {schema} |")
out += [
    "",
    f"Host verbs: {len(host_rows)}.",
    "",
    "## Registry members (fx tools reached as verbs of run_code)",
    "",
    "The schema of each registry tool is a named constant in its own module. Its JSON listing comes from the catalog that run_code builds (run_code.zig buildCatalog), printed by a test; the listing is not yet generated here.",
    "",
    "| registry symbol |",
    "| --- |",
]
for symbol in members:
    out.append(f"| {symbol} |")
out += ["", f"Registry members: {len(members)} (plus run_code itself and the 13 Tower tools listed in docs/host-interface-listing.md)."]
target = root / "docs/verb-table.md"
target.write_text("\n".join(out) + "\n")
print(f"wrote {target.relative_to(root)}: {len(host_rows)} host verbs, {len(members)} registry members")
sys.exit(0)
